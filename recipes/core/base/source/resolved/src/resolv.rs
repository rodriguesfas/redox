//! `/etc/resolv.conf`: the resolver configuration a program reads.
//!
//! The format is the one every Unix writes: comments, a `nameserver` line per
//! resolver, a `search` list, and `options`. Redox reads a small part of it —
//! `relibc` takes the first `nameserver` line and nothing else — but the file
//! is written for whatever reads it, so what is not consumed yet is still kept.
//!
//! The parser is tolerant on purpose: the file is edited by people, written by
//! `resolved`, and read by programs that may not agree with each other. A line
//! that is not understood is kept as it was and reported, never dropped: losing
//! a `search` list because of one bad `nameserver` line would be a poor trade.
//! A comment is the one exception — a comment is not something the file says,
//! and the header of a generated file takes its place.

use std::fmt::Write as _;

use networkd::Ipv4Addr;

/// Where the file lives.
pub const FILE: &str = "/etc/resolv.conf";

/// The resolver configuration of a system.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ResolvConf {
    /// The resolvers, in the order they are tried.
    pub nameservers: Vec<Ipv4Addr>,
    /// The domains to complete a short name with.
    pub search: Vec<String>,
    /// The options, as they were written (`ndots:1`, `timeout:2`, ...).
    pub options: Vec<String>,
    /// The directives this system does not use, kept as they were read.
    ///
    /// Keeping them is what makes a write of the file safe: the file is
    /// regenerated, and a directive that was there before is still there after.
    pub other: Vec<String>,
}

impl ResolvConf {
    /// An empty configuration.
    pub fn new() -> Self {
        Self::default()
    }

    /// Whether the configuration says nothing at all.
    pub fn is_empty(&self) -> bool {
        self.nameservers.is_empty()
            && self.search.is_empty()
            && self.options.is_empty()
            && self.other.is_empty()
    }

    /// The resolver `relibc` would use: the first one written.
    pub fn first(&self) -> Option<Ipv4Addr> {
        self.nameservers.first().copied()
    }

    /// Whether a `search` list is written.
    pub fn has_search(&self) -> bool {
        !self.search.is_empty()
    }

    /// The file as it is written back.
    ///
    /// The first thing written is the line that says where the file comes from,
    /// so reading what was written gives the same configuration back.
    pub fn render(&self) -> String {
        let mut out = String::from(
            "# Generated by resolved from the resolver of the network stack.\n\
             # The lines below are read by the C library and by tools; do not edit.\n",
        );

        for nameserver in &self.nameservers {
            let _ = writeln!(out, "nameserver {nameserver}");
        }
        if !self.search.is_empty() {
            let _ = writeln!(out, "search {}", self.search.join(" "));
        }
        if !self.options.is_empty() {
            let _ = writeln!(out, "options {}", self.options.join(" "));
        }
        for line in &self.other {
            let _ = writeln!(out, "{line}");
        }

        out
    }

    /// The same configuration with the resolvers replaced.
    ///
    /// This is what `resolved` owns: the `nameserver` lines are decided by the
    /// network stack, everything else in the file is left alone.
    pub fn with_nameservers(&self, nameservers: impl IntoIterator<Item = Ipv4Addr>) -> Self {
        Self {
            nameservers: nameservers.into_iter().collect(),
            ..self.clone()
        }
    }

    /// Whether the resolvers of two configurations are the same.
    pub fn same_resolvers(&self, other: &Self) -> bool {
        self.nameservers == other.nameservers
    }
}

/// Parses the file, keeping what is not understood.
pub fn parse(text: &str) -> ResolvConf {
    parse_with_diagnostics(text).0
}

/// Parses the file, and says what is wrong with it.
///
/// The diagnostics name the line, because the file is usually edited by hand
/// and a message that does not say which line is a message that sends the
/// reader looking for it. A line that is kept is still a line that was not
/// understood, so it is reported every time the file is read — including when
/// `resolved` wrote the file the line was kept in.
pub fn parse_with_diagnostics(text: &str) -> (ResolvConf, Vec<String>) {
    let mut conf = ResolvConf::new();
    let mut warnings = Vec::new();

    for (index, raw) in text.lines().enumerate() {
        let line_number = index + 1;
        let line = raw.trim();

        if line.is_empty() || line.starts_with('#') || line.starts_with(';') {
            continue;
        }

        let (directive, rest) = match line.split_once(char::is_whitespace) {
            Some((directive, rest)) => (directive, rest.trim()),
            None => (line, ""),
        };

        match directive {
            "nameserver" => match read_one(rest, line_number, "nameserver", &mut warnings) {
                Some(value) => match value.parse::<Ipv4Addr>() {
                    Ok(nameserver) if nameserver.is_unicast() => conf.nameservers.push(nameserver),
                    Ok(nameserver) => {
                        warnings.push(format!(
                            "line {line_number}: nameserver {nameserver}: not an address a query can be sent to"
                        ));
                        conf.other.push(line.to_owned());
                    }
                    Err(err) => {
                        warnings.push(format!("line {line_number}: nameserver: {err}"));
                        conf.other.push(line.to_owned());
                    }
                },
                None => {
                    warnings.push(format!("line {line_number}: nameserver without an address"));
                    conf.other.push(line.to_owned());
                }
            },
            "search" | "domain" => {
                // `domain` and `search` are the same list, written two ways;
                // the last one in the file is the one that counts.
                if rest.is_empty() {
                    warnings.push(format!("line {line_number}: {directive} without a domain"));
                    conf.other.push(line.to_owned());
                } else {
                    conf.search = rest.split_whitespace().map(str::to_owned).collect();
                }
            }
            "options" => {
                if rest.is_empty() {
                    warnings.push(format!("line {line_number}: options without an option"));
                    conf.other.push(line.to_owned());
                } else {
                    conf.options
                        .extend(rest.split_whitespace().map(str::to_owned));
                }
            }
            other => {
                warnings.push(format!(
                    "line {line_number}: unknown directive {other:?}, kept as it is"
                ));
                conf.other.push(line.to_owned());
            }
        }
    }

    if conf.nameservers.is_empty() && !conf.is_empty() {
        warnings.push("no nameserver: a name cannot be resolved".to_owned());
    }

    (conf, warnings)
}

/// Reads the single value of a directive, reporting what is left over.
///
/// The C library reads the first word of the line and ignores the rest, so a
/// line with more than one address is not what the writer meant and has to be
/// said out loud.
fn read_one(
    rest: &str,
    line_number: usize,
    directive: &str,
    warnings: &mut Vec<String>,
) -> Option<String> {
    let mut parts = rest.split_whitespace();
    let value = parts.next()?;

    if parts.next().is_some() {
        warnings.push(format!(
            "line {line_number}: {directive} takes one value, the rest of the line is ignored"
        ));
    }

    Some(value.to_owned())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn a_nameserver_is_what_the_library_reads() {
        let (conf, warnings) = parse_with_diagnostics("# a comment\nnameserver 9.9.9.9\n");
        assert_eq!(conf.first().unwrap().to_string(), "9.9.9.9");
        assert_eq!(conf.nameservers.len(), 1);
        assert!(!conf.is_empty());
        assert!(warnings.is_empty(), "{warnings:?}");
    }

    #[test]
    fn several_nameservers_keep_their_order() {
        let conf = parse("nameserver 1.1.1.1\nnameserver 9.9.9.9\n");
        assert_eq!(
            conf.nameservers
                .iter()
                .map(|addr| addr.to_string())
                .collect::<Vec<_>>(),
            vec!["1.1.1.1", "9.9.9.9"]
        );
        assert_eq!(conf.first().unwrap().to_string(), "1.1.1.1");
    }

    #[test]
    fn comments_and_empty_lines_are_not_part_of_the_configuration() {
        let conf = parse("# comment\n\n; another\n   \nnameserver 9.9.9.9\n");
        assert_eq!(conf.nameservers.len(), 1);
        assert!(conf.other.is_empty(), "{:?}", conf.other);
    }

    #[test]
    fn the_search_list_is_read_and_the_last_one_wins() {
        let conf = parse("search example.org local\nnameserver 9.9.9.9\n");
        assert_eq!(conf.search, vec!["example.org", "local"]);
        assert!(conf.has_search());

        // `domain` is the other spelling of the same list, so it replaces it.
        let conf = parse("search example.org\ndomain other.test\n");
        assert_eq!(conf.search, vec!["other.test"]);
    }

    #[test]
    fn options_are_read_and_kept_together() {
        let conf = parse("options ndots:1 timeout:2\noptions attempts:3\n");
        assert_eq!(conf.options, vec!["ndots:1", "timeout:2", "attempts:3"]);
    }

    #[test]
    fn what_is_not_understood_is_kept_and_reported() {
        let (conf, warnings) =
            parse_with_diagnostics("sortlist 10.0.0.0/255.0.0.0\nnameserver 9.9.9.9\nrotate\n");

        assert_eq!(conf.nameservers.len(), 1);
        assert_eq!(
            conf.other,
            vec!["sortlist 10.0.0.0/255.0.0.0", "rotate"],
            "the lines are kept as they were"
        );
        assert_eq!(warnings.len(), 2, "{warnings:?}");
        assert!(
            warnings[0].contains("line 1: unknown directive \"sortlist\""),
            "{warnings:?}"
        );
        assert!(
            warnings[1].contains("line 3: unknown directive \"rotate\""),
            "{warnings:?}"
        );
    }

    #[test]
    fn a_nameserver_that_is_not_one_is_reported_and_kept() {
        for (text, expected) in [
            ("nameserver\n", "line 1: nameserver without an address"),
            (
                "nameserver banana\n",
                "nameserver: banana: not an IPv4 address",
            ),
            (
                "nameserver 10.0.0.300\n",
                "nameserver: 10.0.0.300: octet out of range",
            ),
            (
                "nameserver 224.0.0.1\n",
                "not an address a query can be sent to",
            ),
            (
                "nameserver 0.0.0.0\n",
                "not an address a query can be sent to",
            ),
        ] {
            let (conf, warnings) = parse_with_diagnostics(text);
            assert!(
                conf.nameservers.is_empty(),
                "{text:?}: {:?}",
                conf.nameservers
            );
            assert!(
                warnings.iter().any(|warning| warning.contains(expected)),
                "{text:?}: {warnings:?}"
            );

            // Nothing was dropped: a line that is not a resolver is not a line
            // to lose, because the next write of the file writes it back.
            assert_eq!(conf.other.len(), 1, "{text:?}: {:?}", conf.other);
        }
    }

    #[test]
    fn a_nameserver_with_two_addresses_says_that_only_one_is_read() {
        let (conf, warnings) = parse_with_diagnostics("nameserver 9.9.9.9 1.1.1.1\n");
        assert_eq!(conf.nameservers.len(), 1);
        assert!(
            warnings[0].contains("nameserver takes one value"),
            "{warnings:?}"
        );
    }

    #[test]
    fn a_file_with_no_resolver_says_so() {
        let (conf, warnings) = parse_with_diagnostics("search example.org\n");
        assert!(conf.nameservers.is_empty());
        assert_eq!(warnings, vec!["no nameserver: a name cannot be resolved"]);

        // An empty file says nothing, and there is nothing to complain about.
        let (conf, warnings) = parse_with_diagnostics("");
        assert!(conf.is_empty());
        assert!(warnings.is_empty());
    }

    #[test]
    fn the_file_is_written_and_read_back_the_same_way() {
        let conf = ResolvConf {
            nameservers: vec!["9.9.9.9".parse().unwrap(), "1.1.1.1".parse().unwrap()],
            search: vec!["example.org".to_owned(), "local".to_owned()],
            options: vec!["ndots:1".to_owned()],
            other: vec!["sortlist 10.0.0.0/255.0.0.0".to_owned()],
        };

        let written = conf.render();
        assert!(written.starts_with("# Generated by resolved"), "{written}");
        assert!(written.contains("nameserver 9.9.9.9\n"), "{written}");
        assert!(written.contains("nameserver 1.1.1.1\n"), "{written}");
        assert!(written.contains("search example.org local\n"), "{written}");
        assert!(written.contains("options ndots:1\n"), "{written}");
        assert!(
            written.contains("sortlist 10.0.0.0/255.0.0.0\n"),
            "{written}"
        );

        let (again, warnings) = parse_with_diagnostics(&written);
        assert_eq!(again, conf);

        // The line that was kept is still a line that was not understood, and
        // saying so again is the point: it is in the file, and it is not ours.
        assert_eq!(warnings.len(), 1, "{warnings:?}");
        assert!(
            warnings[0].contains("unknown directive \"sortlist\""),
            "{warnings:?}"
        );
    }

    #[test]
    fn a_configuration_with_no_resolver_is_written_as_such() {
        let conf = ResolvConf::new();
        assert_eq!(conf.render().lines().count(), 2, "only the comment");
        assert!(conf.first().is_none());
        assert!(conf.is_empty());
    }

    #[test]
    fn the_resolvers_can_be_replaced_and_nothing_else_moves() {
        let conf = parse("nameserver 9.9.9.9\nsearch example.org\noptions ndots:1\n");
        let updated = conf.with_nameservers(["1.1.1.1".parse().unwrap()]);

        assert_eq!(updated.first().unwrap().to_string(), "1.1.1.1");
        assert_eq!(updated.search, conf.search);
        assert_eq!(updated.options, conf.options);
        assert!(!conf.same_resolvers(&updated));
        assert!(conf.same_resolvers(&conf.with_nameservers(["9.9.9.9".parse().unwrap()])));
    }
}
